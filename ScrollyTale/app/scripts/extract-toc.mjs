/**
 * Reads the reader's own files and writes what the player needs.
 *
 *   assets/toc.js      -> src/data/toc.generated.ts   (units, chapters)
 *   chapters/*.html    -> src/data/concepts.generated.json
 *      each glossary term with its definition, the notion of what its definition
 *      is built on and what leads to it, and the section that first teaches it.
 *
 * Nothing is hand-maintained here: the reader stays the source of truth.
 * Re-run with: npm run toc
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { runInNewContext } from "node:vm";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../../..");
const tocPath = resolve(repoRoot, "assets/toc.js");

const sandbox = { window: {} };
runInNewContext(readFileSync(tocPath, "utf8"), sandbox);
const COURSE = sandbox.window.COURSE;
if (!COURSE || !Array.isArray(COURSE.chapters)) {
  throw new Error("assets/toc.js did not define window.COURSE.chapters");
}

// ---------------------------------------------------------------- toc
const ready = COURSE.chapters.filter((c) => (c.status ?? "ready") === "ready");
const units = COURSE.units.map((u) => ({
  id: u.id,
  label: u.label ?? u.id,
  short: u.short ?? u.id,
  hue: u.hue ?? null,
  needs: u.needs ?? [],
}));

const chapters = ready.map((c) => ({
  id: c.id,
  file: c.file,
  unit: c.unit,
  title: c.title,
  summary: c.summary ?? "",
  question: c.question ?? "",
  time: c.time ?? "",
  sections: c.sections ?? 0,
  standards: c.standards ?? [],
  kind: c.kind ?? "Lesson",
  status: c.status ?? "ready",
  sims: c.sims ?? [],
}));

const tocOut = resolve(here, "../src/data/toc.generated.ts");
writeFileSync(
  tocOut,
  "/* GENERATED by scripts/extract-toc.mjs from assets/toc.js. Do not edit by hand. */\n" +
    "export interface TocChapter {\n" +
    "  id: string;\n  file: string;\n  unit: string;\n  title: string;\n  summary: string;\n" +
    "  question: string;\n  time: string;\n  sections: number;\n" +
    "  standards: string[];\n  kind: string;\n  status: string;\n  sims: string[];\n}\n\n" +
    "export interface TocUnit {\n  id: string;\n  label: string;\n  short: string;\n  hue: number | null;\n  needs: string[];\n}\n\n" +
    `export const UNITS: TocUnit[] = ${JSON.stringify(units, null, 2)};\n\n` +
    `export const CHAPTERS: TocChapter[] = ${JSON.stringify(chapters, null, 2)};\n\n` +
    "export const UNIT_2_CHAPTERS: TocChapter[] = CHAPTERS.filter((c) => c.unit === \"u2\");\n",
  "utf8",
);

// ---------------------------------------------------------------- sections
/** Every tracked or ordinary section in a chapter, in reading order. */
function sectionsOf(html) {
  const out = [];
  const open = /<section\b([^>]*)>/gi;
  let m;
  while ((m = open.exec(html))) {
    const attrs = m[1];
    const id = /id="([^"]+)"/.exec(attrs)?.[1];
    if (!id) continue;

    const start = m.index + m[0].length;
    const tags = /<\/?section\b[^>]*>/gi;
    tags.lastIndex = start;
    let depth = 1;
    let end = html.length;
    let t;
    while ((t = tags.exec(html))) {
      depth += t[0].startsWith("</") ? -1 : 1;
      if (depth === 0) {
        end = t.index;
        break;
      }
    }

    const body = html.slice(start, end);
    const heading = /<h2\b[^>]*>([\s\S]*?)<\/h2>/i.exec(body)?.[1]?.replace(/<[^>]+>/g, "").trim() ?? "";
    const text = body
      .replace(/<[^>]+>/g, " ")
      .replace(/&[a-z]+;/gi, " ")
      .replace(/\s+/g, " ")
      .trim();

    out.push({ id, heading, text });
  }
  return out;
}

const sectionIndex = [];
for (const chapter of chapters) {
  const file = resolve(repoRoot, chapter.file);
  if (!existsSync(file)) continue;
  for (const section of sectionsOf(readFileSync(file, "utf8"))) {
    sectionIndex.push({ chapter: chapter.id, unit: chapter.unit, ...section });
  }
}

// ---------------------------------------------------------------- terms
// The same rules the reader's word map uses, so the two never disagree about
// whether two words are related.
function forms(key) {
  const w = key.toLowerCase();
  const f = new Set([w, w + "s", w + "es"]);
  if (/[^aeiou]y$/.test(w)) f.add(w.slice(0, -1) + "ies");
  if (/us$/.test(w)) f.add(w.slice(0, -2) + "i");
  if (/um$/.test(w)) f.add(w.slice(0, -2) + "a");
  if (/on$/.test(w)) f.add(w.slice(0, -2) + "a");
  if (/is$/.test(w)) f.add(w.slice(0, -2) + "es");
  if (/a$/.test(w)) f.add(w + "e");
  return [...f].sort((a, b) => b.length - a.length);
}

const NOT_A_TERM = [
  /\bno matter\b/gi,
  /\bcarrier molecules?\b/gi,
  /\bequal rates?\b/gi,
];

const G = COURSE.glossary ?? {};
const KEYS = Object.keys(G);
const reEsc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const matchers = KEYS.map((k) => ({
  k,
  re: new RegExp("\\b(?:" + forms(k).map(reEsc).join("|") + ")\\b", "gi"),
})).sort((a, b) => b.k.length - a.k.length);

function uses(text) {
  let scan = String(text);
  for (const guard of NOT_A_TERM) scan = scan.replace(guard, " ");
  const found = new Set();
  for (const { k, re } of matchers) {
    re.lastIndex = 0;
    if (re.test(scan)) found.add(k);
  }
  return found;
}

const builtOn = {};
const leadsTo = {};
const terms = {};

for (const key of KEYS) {
  terms[key] = { definition: String(G[key]), builtOn: [], leadsTo: [], teaches: null };
  builtOn[key] = new Set();
  leadsTo[key] = new Set();
}

for (const key of KEYS) {
  for (const used of uses(G[key])) {
    if (used === key) continue;
    builtOn[key].add(used);
    leadsTo[used].add(key);
  }
}

// Sections that list or check ideas rather than teach them. A word mentioned in
// a unit's learning targets has not been taught there, so these are only used
// when nothing else mentions it.
const META_SECTIONS = new Set([
  "overview", "standards", "targets", "what-you-do", "check", "do-it", "do-it-again",
]);

// The section that first teaches a word: a heading that names it, then ordinary
// teaching text, then a listing or checking section as a last resort.
for (const key of KEYS) {
  const re = new RegExp("\\b(?:" + forms(key).map(reEsc).join("|") + ")\\b", "i");
  const inHeading = sectionIndex.find((s) => re.test(s.heading));
  const inText = sectionIndex.find((s) => !META_SECTIONS.has(s.id) && re.test(s.text));
  const inMeta = sectionIndex.find((s) => re.test(s.text));
  const anywhere = inHeading ?? inText ?? inMeta;
  if (anywhere) {
    terms[key].teaches = {
      chapter: anywhere.chapter,
      section: anywhere.id,
      heading: anywhere.heading,
      unit: anywhere.unit,
    };
  }
}

for (const key of KEYS) {
  terms[key].builtOn = [...builtOn[key]].sort();
  terms[key].leadsTo = [...leadsTo[key]].sort();
}

// Which glossary words each section mentions, for questions that name none.
const sections = sectionIndex
  .map((s) => {
    const found = new Set();
    const words = new Set(
      s.text
        .toLowerCase()
        .replace(/[^a-z0-9\s'-]/g, " ")
        .split(/\s+/)
        .filter((w) => w.length > 3),
    );
    for (const key of KEYS) {
      const forms_ = forms(key).map((f) => f.toLowerCase());
      if (forms_.some((f) => words.has(f))) found.add(key);
    }
    return {
      chapter: s.chapter,
      unit: s.unit,
      id: s.id,
      heading: s.heading,
      terms: [...found].sort(),
    };
  })
  .filter((s) => s.heading && s.terms.length > 0);

const conceptsOut = resolve(here, "../src/data/concepts.generated.json");
writeFileSync(conceptsOut, JSON.stringify({ terms, sections }, null, 1), "utf8");
console.log(`sections with terms : ${sections.length}`);

const withEdges = KEYS.filter((k) => terms[k].builtOn.length || terms[k].leadsTo.length).length;
const withPlace = KEYS.filter((k) => terms[k].teaches).length;
console.log(`toc      : ${chapters.length} ready chapters, ${units.length} units`);
console.log(`sections : ${sectionIndex.length} indexed`);
console.log(`terms    : ${KEYS.length} (${withEdges} with relations, ${withPlace} with a teaching section)`);
