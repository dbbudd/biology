/**
 * Reads the reader's assets/toc.js and writes Unit 2 metadata for the player.
 *
 * The reader owns chapter titles, times, questions and standards. This script
 * copies them at build time so the tale never hand-maintains a second copy.
 * Re-run with: npm run toc
 */
import { readFileSync, writeFileSync } from "node:fs";
import { runInNewContext } from "node:vm";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../../..");
const tocPath = resolve(repoRoot, "assets/toc.js");

const sandbox = { window: {} };
runInNewContext(readFileSync(tocPath, "utf8"), sandbox);
const COURSE = sandbox.window.COURSE;

if (!COURSE || !Array.isArray(COURSE.chapters)) {
  throw new Error("assets/toc.js did not define window.COURSE.chapters");
}

const unit = COURSE.units.find((u) => u.id === "u2");
if (!unit) throw new Error("Unit 2 is missing from COURSE.units");

const chapters = COURSE.chapters
  .filter((c) => c.unit === "u2")
  .map((c) => ({
    id: c.id,
    file: c.file,
    title: c.title,
    summary: c.summary ?? "",
    question: c.question ?? "",
    time: c.time ?? "",
    sections: c.sections ?? 0,
    standards: c.standards ?? [],
    kind: c.kind ?? "Lesson",
    status: c.status ?? "ready",
    sims: c.sims ?? [],
  }));

const payload = {
  unit: {
    id: unit.id,
    label: unit.label ?? unit.id,
    short: unit.short ?? unit.id,
    hue: unit.hue ?? null,
    needs: unit.needs ?? [],
  },
  chapters,
};

const out = resolve(here, "../src/data/toc.u2.generated.ts");
const body =
  "/* GENERATED by scripts/extract-toc.mjs from assets/toc.js. Do not edit by hand. */\n" +
  "export interface TocChapter {\n" +
  "  id: string;\n  file: string;\n  title: string;\n  summary: string;\n" +
  "  question: string;\n  time: string;\n  sections: number;\n" +
  "  standards: string[];\n  kind: string;\n  status: string;\n  sims: string[];\n}\n\n" +
  "export interface TocUnit {\n  id: string;\n  label: string;\n  short: string;\n  hue: number | null;\n  needs: string[];\n}\n\n" +
  `export const UNIT_2: TocUnit = ${JSON.stringify(payload.unit, null, 2)};\n\n` +
  `export const UNIT_2_CHAPTERS: TocChapter[] = ${JSON.stringify(chapters, null, 2)};\n`;

writeFileSync(out, body, "utf8");
console.log(`wrote ${out} with ${chapters.length} Unit 2 chapters`);
