            '   padding:0.4rem 0.7rem; border:1px solid var(--border); border-radius:8px;',
            '   background:var(--bg); color:var(--text); touch-action:manipulation; }',
            '.ia-opt:hover { border-color:var(--light-teal); }',
            '.ia-opt.right { border-color:var(--ia-ok); color:var(--ia-ok); }',
            '.ia-opt.wrong { border-color:var(--ia-bad); color:var(--ia-bad); opacity:0.55; }',
            '.ia-grid { display:grid; gap:0.5rem; margin:0.85rem 0 0;',
