            '   background:var(--bg); }',
            '.ia-card svg { display:block; width:100%; height:auto; }',
            '.ia-card p { margin:0.25rem 0 0; font-size:0.62rem; color:var(--text-secondary);',
            '   text-align:center; letter-spacing:0.03em; }',
            '.ia-sum { display:flex; gap:0.8rem; flex-wrap:wrap; margin:0.9rem 0 0; }',
            '.ia-stat { border:1px solid var(--border); border-radius:9px; padding:0.5rem 0.7rem;',
            '   min-width:120px; }',
            '.ia-stat small { display:block; color:var(--text-secondary); font-size:0.64rem;',
            '   text-transform:uppercase; letter-spacing:0.05em; font-weight:700; }',
            '.ia-stat b { font-size:1.25rem; line-height:1.2; }',
            '.ia-big { margin-top:1rem; border:1px solid var(--ia-ok); border-radius:10px;',
            '   background:rgba(46,125,50,0.08); padding:0.9rem 1rem; }',
            '[data-theme="dark"] .ia-big { background:rgba(127,201,138,0.12); }',
            '.ia-big h5 { margin:0 0 0.5rem; font-size:0.9rem; }',
            '.ia-big p { margin:0 0 0.6rem; font-size:0.84rem; line-height:1.6; }',
            '.ia-big p:last-child { margin-bottom:0; }',
            '.ia-huge { font-size:1.6rem; font-weight:800; letter-spacing:-0.01em; display:block;',
            '   margin:0.3rem 0 0.15rem; }',
            '.ia-table { width:100%; border-collapse:collapse; margin-top:0.8rem; font-size:0.8rem; }',
            '.ia-table th, .ia-table td { border-bottom:1px solid var(--border); padding:0.32rem 0.45rem;',
            '   text-align:right; }',
            '.ia-table th:first-child, .ia-table td:first-child { text-align:left; }',
            '.ia-table thead th { font-size:0.64rem; text-transform:uppercase; letter-spacing:0.05em;',
            '   color:var(--text-secondary); }',
            '.ia-table tr.now td { font-weight:800; color:var(--text); }',
            '.ia-msg { font-size:0.83rem; line-height:1.6; margin:0.6rem 0 0; min-height:2.4em; }',
            '.ia-msg.ok { color:var(--ia-ok); } .ia-msg.bad { color:var(--ia-bad); }',
            '.ia-msg b { color:var(--text); }',
            '.ia-roll { margin-top:0.9rem; border:1px solid var(--border); border-radius:10px;',
